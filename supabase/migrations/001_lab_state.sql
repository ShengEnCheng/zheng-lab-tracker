create extension if not exists pgcrypto;

do $$ begin
  create type public.lab_role as enum ('researcher', 'study_manager', 'admin', 'backup_admin');
exception when duplicate_object then null;
end $$;

create table if not exists public.lab_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text,
  role public.lab_role not null default 'researcher',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lab_state (
  id integer primary key check (id = 1),
  data jsonb not null,
  revision bigint not null default 1 check (revision >= 1),
  schema_version integer not null default 1,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.lab_audit_logs (
  id bigint generated by default as identity primary key,
  request_id uuid not null unique,
  action text not null check (action in ('change', 'import', 'restore', 'backup')),
  base_revision bigint,
  resulting_revision bigint,
  actor_id uuid references auth.users(id),
  entity_summary jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.lab_backups (
  id uuid primary key default gen_random_uuid(),
  source_revision bigint not null,
  schema_version integer not null,
  data jsonb not null,
  checksum text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  kind text not null default 'scheduled' check (kind in ('scheduled', 'weekly', 'before_import', 'before_restore', 'migration'))
);

create table if not exists public.lab_backup_runs (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('scheduled', 'weekly')),
  status text not null check (status in ('running', 'succeeded', 'failed')),
  attempts integer not null default 1 check (attempts >= 1),
  backup_id uuid references public.lab_backups(id),
  source_revision bigint,
  error_message text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

alter table public.lab_profiles enable row level security;
alter table public.lab_state enable row level security;
alter table public.lab_audit_logs enable row level security;
alter table public.lab_backups enable row level security;
alter table public.lab_backup_runs enable row level security;

create or replace function public.current_lab_role()
returns public.lab_role
language sql stable security definer set search_path = public
as $$
  select role from public.lab_profiles where id = auth.uid() and active = true limit 1;
$$;

create or replace function public.can_use_lab_data()
returns boolean
language sql stable security definer set search_path = public
as $$
  select public.current_lab_role() is not null;
$$;

drop policy if exists "active users can read profile" on public.lab_profiles;
create policy "active users can read profile"
on public.lab_profiles for select
using (id = auth.uid() or public.current_lab_role() in ('admin', 'backup_admin'));

drop policy if exists "active users can read state" on public.lab_state;
create policy "active users can read state"
on public.lab_state for select
using (public.can_use_lab_data());

drop policy if exists "admins can read audit" on public.lab_audit_logs;
create policy "admins can read audit"
on public.lab_audit_logs for select
using (public.current_lab_role() in ('admin', 'backup_admin'));

drop policy if exists "admins can read backups" on public.lab_backups;
create policy "admins can read backups"
on public.lab_backups for select
using (public.current_lab_role() in ('admin', 'backup_admin'));

drop policy if exists "admins can read backup runs" on public.lab_backup_runs;
create policy "admins can read backup runs"
on public.lab_backup_runs for select
using (public.current_lab_role() in ('admin', 'backup_admin'));

create or replace function public.jsonb_sha256(p_data jsonb)
returns text
language sql immutable strict
as $$
  select encode(extensions.digest(convert_to(p_data::text, 'UTF8'), 'sha256'), 'hex');
$$;

create or replace function public.create_lab_backup(p_kind text default 'scheduled')
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  current_row public.lab_state%rowtype;
  backup_row public.lab_backups%rowtype;
begin
  if p_kind not in ('scheduled', 'weekly') then raise exception 'invalid_backup_kind'; end if;
  select * into current_row from public.lab_state where id = 1;
  if current_row.id is null then raise exception 'data_not_found'; end if;
  insert into public.lab_backups(source_revision, schema_version, data, checksum, kind)
  values (current_row.revision, current_row.schema_version, current_row.data, public.jsonb_sha256(current_row.data), p_kind)
  returning * into backup_row;
  return jsonb_build_object('backupId', backup_row.id, 'sourceRevision', backup_row.source_revision,
    'checksum', backup_row.checksum, 'createdAt', backup_row.created_at, 'kind', backup_row.kind);
end;
$$;

create or replace function public.prune_lab_backups(p_daily_keep integer default 30, p_weekly_keep integer default 12)
returns integer
language plpgsql security definer set search_path = public
as $$
declare deleted_count integer;
begin
  if auth.role() <> 'service_role' and public.current_lab_role() not in ('admin', 'backup_admin') then raise exception 'not_authorized'; end if;
  with keep_daily as (
    select id from public.lab_backups where kind = 'scheduled' order by created_at desc limit greatest(p_daily_keep, 0)
  ), keep_weekly as (
    select id from public.lab_backups where kind = 'weekly' order by created_at desc limit greatest(p_weekly_keep, 0)
  ), doomed as (
    select id from public.lab_backups where kind = 'scheduled' and id not in (select id from keep_daily)
    union all
    select id from public.lab_backups where kind = 'weekly' and id not in (select id from keep_weekly)
  )
  delete from public.lab_backups where id in (select id from doomed);
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

create or replace function public.apply_lab_state_change(
  p_base_revision bigint,
  p_request_id uuid,
  p_data jsonb
)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  current_row public.lab_state%rowtype;
  next_revision bigint;
  actor uuid := auth.uid();
  existing_log public.lab_audit_logs%rowtype;
begin
  if public.current_lab_role() is null then
    raise exception 'not_authorized';
  end if;

  select * into existing_log from public.lab_audit_logs where request_id = p_request_id;
  if existing_log.id is not null then
    return jsonb_build_object('revision', existing_log.resulting_revision, 'changeId', existing_log.id, 'idempotent', true);
  end if;

  select * into current_row from public.lab_state where id = 1 for update;
  if current_row.id is null then
    insert into public.lab_state(id, data, revision, schema_version, updated_by)
    values (1, p_data, 1, coalesce((p_data->>'schemaVersion')::integer, 1), actor)
    returning * into current_row;
    next_revision := current_row.revision;
  elsif current_row.revision <> p_base_revision then
    raise exception 'revision_conflict: expected %, current %', p_base_revision, current_row.revision;
  else
    next_revision := current_row.revision + 1;
    update public.lab_state
       set data = p_data,
           revision = next_revision,
           schema_version = coalesce((p_data->>'schemaVersion')::integer, schema_version),
           updated_at = now(),
           updated_by = actor
     where id = 1;
  end if;

  insert into public.lab_audit_logs(request_id, action, base_revision, resulting_revision, actor_id, entity_summary)
  values (p_request_id, 'change', p_base_revision, next_revision, actor,
          jsonb_build_object('dataKeys', (select jsonb_agg(key) from jsonb_object_keys(p_data) as key)));

  return jsonb_build_object('revision', next_revision, 'requestId', p_request_id, 'updatedAt', now());
end;
$$;

revoke all on function public.apply_lab_state_change(bigint, uuid, jsonb) from public;
grant execute on function public.apply_lab_state_change(bigint, uuid, jsonb) to authenticated;

create or replace function public.import_lab_state(
  p_data jsonb,
  p_request_id uuid
)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  current_row public.lab_state%rowtype;
  snapshot_id uuid;
  next_revision bigint;
  actor uuid := auth.uid();
  existing_log public.lab_audit_logs%rowtype;
begin
  if public.current_lab_role() not in ('admin', 'backup_admin') then
    raise exception 'not_authorized';
  end if;
  select * into existing_log from public.lab_audit_logs where request_id = p_request_id;
  if existing_log.id is not null then
    return jsonb_build_object('revision', existing_log.resulting_revision, 'requestId', p_request_id, 'idempotent', true);
  end if;
  select * into current_row from public.lab_state where id = 1 for update;
  if current_row.id is not null then
    insert into public.lab_backups(source_revision, schema_version, data, checksum, created_by, kind)
    values (current_row.revision, current_row.schema_version, current_row.data, public.jsonb_sha256(current_row.data), actor, 'before_import')
    returning id into snapshot_id;
    next_revision := current_row.revision + 1;
    update public.lab_state set data = p_data, revision = next_revision,
      schema_version = coalesce((p_data->>'schemaVersion')::integer, current_row.schema_version),
      updated_at = now(), updated_by = actor where id = 1;
  else
    next_revision := 1;
    insert into public.lab_state(id, data, revision, schema_version, updated_by)
    values (1, p_data, next_revision, coalesce((p_data->>'schemaVersion')::integer, 1), actor);
  end if;
  insert into public.lab_audit_logs(request_id, action, base_revision, resulting_revision, actor_id, entity_summary)
  values (p_request_id, 'import', current_row.revision, next_revision, actor,
          jsonb_build_object('beforeSnapshotId', snapshot_id));
  return jsonb_build_object('revision', next_revision, 'beforeSnapshotId', snapshot_id, 'requestId', p_request_id, 'updatedAt', now());
end;
$$;

revoke all on function public.import_lab_state(jsonb, uuid) from public;
grant execute on function public.import_lab_state(jsonb, uuid) to authenticated;

create or replace function public.restore_lab_backup(
  p_backup_id uuid,
  p_request_id uuid
)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  backup_row public.lab_backups%rowtype;
  current_row public.lab_state%rowtype;
  next_revision bigint;
  before_restore_id uuid;
  actor uuid := auth.uid();
  existing_log public.lab_audit_logs%rowtype;
begin
  if public.current_lab_role() not in ('admin', 'backup_admin') then
    raise exception 'not_authorized';
  end if;
  select * into existing_log from public.lab_audit_logs where request_id = p_request_id;
  if existing_log.id is not null then
    return jsonb_build_object('revision', existing_log.resulting_revision, 'requestId', p_request_id, 'idempotent', true);
  end if;

  select * into backup_row from public.lab_backups where id = p_backup_id;
  if backup_row.id is null then raise exception 'backup_not_found'; end if;
  if backup_row.checksum is not null and backup_row.checksum <> public.jsonb_sha256(backup_row.data) then
    raise exception 'backup_integrity_failed';
  end if;

  select * into current_row from public.lab_state where id = 1 for update;
  if current_row.id is not null then
    insert into public.lab_backups(source_revision, schema_version, data, checksum, created_by, kind)
    values (current_row.revision, current_row.schema_version, current_row.data, public.jsonb_sha256(current_row.data), actor, 'before_restore')
    returning id into before_restore_id;
  end if;
  next_revision := coalesce(current_row.revision, 0) + 1;
  update public.lab_state
     set data = backup_row.data,
         revision = next_revision,
         schema_version = backup_row.schema_version,
         updated_at = now(),
         updated_by = actor
   where id = 1;

  insert into public.lab_audit_logs(request_id, action, base_revision, resulting_revision, actor_id, entity_summary)
  values (p_request_id, 'restore', current_row.revision, next_revision, actor,
          jsonb_build_object('sourceBackupId', p_backup_id, 'sourceRevision', backup_row.source_revision, 'beforeRestoreSnapshotId', before_restore_id));

  return jsonb_build_object('revision', next_revision, 'sourceBackupId', p_backup_id, 'beforeRestoreSnapshotId', before_restore_id, 'requestId', p_request_id, 'updatedAt', now());
end;
$$;

revoke all on function public.restore_lab_backup(uuid, uuid) from public;
grant execute on function public.restore_lab_backup(uuid, uuid) to authenticated;
grant execute on function public.jsonb_sha256(jsonb) to service_role;
grant execute on function public.create_lab_backup(text) to service_role;
grant execute on function public.prune_lab_backups(integer, integer) to authenticated;
grant execute on function public.prune_lab_backups(integer, integer) to service_role;
